"""Modelo de datos BORE (sección 7.1). SQLAlchemy Core; JSONB solo para
material de investigación flexible; fechas timestamptz en UTC."""

from __future__ import annotations

import sqlalchemy as sa
from sqlalchemy.dialects import postgresql as pg

metadata = sa.MetaData()

utcnow = sa.func.now()

research_runs = sa.Table(
    "research_runs",
    metadata,
    sa.Column("id", pg.UUID(as_uuid=True), primary_key=True),
    sa.Column("sector", sa.Text, nullable=False),
    sa.Column("country", sa.Text, nullable=False),
    sa.Column("language", sa.Text, nullable=False),
    sa.Column("config", pg.JSONB, nullable=False),
    sa.Column("status", sa.Text, nullable=False),
    sa.Column("stop_reason", sa.Text, nullable=True),
    sa.Column("current_stage", sa.Text, nullable=True),
    sa.Column("progress_percent", sa.Integer, nullable=False, server_default="0"),
    sa.Column("created_at", sa.DateTime(timezone=True), server_default=utcnow, nullable=False),
    sa.Column("started_at", sa.DateTime(timezone=True), nullable=True),
    sa.Column("finished_at", sa.DateTime(timezone=True), nullable=True),
    sa.Column("heartbeat_at", sa.DateTime(timezone=True), nullable=True),
    sa.Column("cancel_requested_at", sa.DateTime(timezone=True), nullable=True),
    sa.Column("error_code", sa.Text, nullable=True),
    sa.Column("error_message_safe", sa.Text, nullable=True),
    sa.Column("prompt_version", sa.Text, nullable=True),
    sa.Column("rubric_version", sa.Text, nullable=True),
    sa.Column("pricing_version", sa.Text, nullable=True),
    sa.Column("model_config", pg.JSONB, nullable=True),
    sa.Column("estimated_cost_usd", sa.Numeric(10, 4), nullable=True),
    sa.Column("actual_cost_usd", sa.Numeric(10, 4), nullable=True),
    sa.Column("cost_is_estimated", sa.Boolean, nullable=False, server_default=sa.false()),
    sa.Column("tokens_input", sa.BigInteger, nullable=False, server_default="0"),
    sa.Column("tokens_output", sa.BigInteger, nullable=False, server_default="0"),
    sa.Column("web_search_calls", sa.Integer, nullable=False, server_default="0"),
    sa.Column("model_calls", sa.Integer, nullable=False, server_default="0"),
    sa.Column("trace_id", sa.Text, nullable=True),
    sa.Column("rq_job_id", sa.Text, nullable=True),
    sa.Column("requeue_count", sa.Integer, nullable=False, server_default="0"),
    sa.Column("is_synthetic", sa.Boolean, nullable=False, server_default=sa.false()),
    sa.Index("ix_research_runs_status", "status"),
    sa.Index("ix_research_runs_created", "created_at"),
)

